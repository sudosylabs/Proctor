import {readFile, writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const siteDirectory = path.resolve(scriptDirectory, '..');
const repositoryDirectory = path.resolve(siteDirectory, '../..');
const environmentSourcePath = path.join(repositoryDirectory, 'server/config/environment_overlay.go');
const outputPath = path.join(repositoryDirectory, 'docs/public/reference/environment-variables.mdx');
const cliReferencePath = path.join(repositoryDirectory, 'docs/public/reference/command-line.mdx');
const cliSourceDirectory = path.join(repositoryDirectory, 'server/cmd/proctor/commands');

const source = await readFile(environmentSourcePath, 'utf8');
const matcher = /(stringList|string|duration|int64|int|bool|scalar|console)EnvironmentOverride\(\s*"(PROCTOR_[A-Z0-9_]+)"/g;
const variables = [];
const seen = new Set();

for (const match of source.matchAll(matcher)) {
  const [, parser, name] = match;
  if (seen.has(name)) {
    throw new Error(`duplicate environment variable ${name}`);
  }
  seen.add(name);
  variables.push({name, parser});
}

if (variables.length !== 122) {
  throw new Error(`expected 122 environment overrides, found ${variables.length}`);
}

const typeLabel = {
  stringList: 'comma-separated strings',
  string: 'string',
  duration: 'Go duration',
  int64: 'integer',
  int: 'integer',
  bool: 'boolean',
  scalar: 'closed string',
  console: 'string',
};

const groupOrder = [
  'Server', 'Metrics', 'Database', 'Cache', 'Cluster', 'Mail', 'VFS',
  'Execution', 'Authentication', 'Log',
];
const groups = new Map(groupOrder.map((group) => [group, []]));
for (const variable of variables) {
  const key = variable.name.split('_')[1];
  const group = key === 'VFS' ? 'VFS' : key[0] + key.slice(1).toLowerCase();
  if (!groups.has(group)) {
    throw new Error(`environment variable ${variable.name} has unknown group ${group}`);
  }
  groups.get(group).push(variable);
}

const lines = [
  '---',
  'title: Environment Variable Reference',
  'description: Generated inventory of the validated PROCTOR_ deployment overrides implemented by the server.',
  'audience: operator',
  'maturity: preview',
  'slug: /reference/environment-variables/',
  'pagination_next: null',
  '---',
  '',
  '# Environment Variable Reference',
  '',
  '{/* Generated by docs/site/scripts/technical-reference.mjs. Do not edit by hand. */}',
  '',
  `This checked inventory contains all ${variables.length} process-level overrides accepted by`,
  '`server/config/environment_overlay.go`. An override wins over the persisted JSON value',
  'for the running process and is never written back to the configuration file.',
  '',
  'Unset variables do not override JSON. Empty values are still values and are validated',
  'according to the target field; they do not universally mean “unset”.',
  '',
];

for (const group of groupOrder) {
  const entries = groups.get(group);
  lines.push(`## ${group}`, '', '| Variable | Accepted representation |', '| --- | --- |');
  for (const entry of entries) {
    lines.push(`| \`${entry.name}\` | ${typeLabel[entry.parser]} |`);
  }
  lines.push('');
}

lines.push(
  '## Source and Validation',
  '',
  'The corresponding JSON shape and safe synthetic defaults live in',
  '[`server/config/config.example.json`](https://github.com/sudosylabs/Proctor/blob/main/server/config/config.example.json).',
  'Validate the complete effective configuration before starting Proctor:',
  '',
  '```sh',
  'proctor config validate --config /etc/proctor/config.json',
  '```',
  '',
);

const generated = `${lines.join('\n')}\n`;
const check = process.argv.includes('--check');
if (check) {
  const current = await readFile(outputPath, 'utf8').catch(() => '');
  if (current !== generated) {
    throw new Error('environment variable reference is stale; run npm run generate:technical-reference');
  }

  const cliReference = await readFile(cliReferencePath, 'utf8');
  const cliSources = await Promise.all(
    ['root.go', 'serve.go', 'config.go', 'migrate.go', 'administrator.go', 'version.go']
      .map((filename) => readFile(path.join(cliSourceDirectory, filename), 'utf8')),
  );
  const cliSource = cliSources.join('\n');
  const requiredCLI = [
    'proctor serve',
    'proctor config validate',
    'proctor migrate status',
    'proctor migrate up',
    'proctor administrator recover',
    'proctor version',
    '--config',
    '--institution-id',
    '--user-id',
    '--enable-local-login',
    '--rotate-password',
    '--json',
  ];
  for (const token of requiredCLI) {
    if (!cliReference.includes(token)) {
      throw new Error(`command-line reference is missing ${token}`);
    }
  }
  const requiredSourceContracts = [
    'newServeCommand',
    'newConfigCommand',
    'newMigrateCommand',
    'newAdministratorCommand',
    'newVersionCommand',
    'Use:   "serve"',
    'Use:   "validate"',
    'Use:   "up"',
    'Use:   "status"',
    'Use:   "recover"',
    'Use:   "version"',
    '"config"',
    '"institution-id"',
    '"user-id"',
    '"enable-local-login"',
    '"rotate-password"',
    '"json"',
  ];
  for (const token of requiredSourceContracts) {
    if (!cliSource.includes(token)) {
      throw new Error(`command-line source no longer declares ${token}`);
    }
  }
  process.stdout.write(`Technical reference is current: ${variables.length} environment overrides and ${requiredCLI.length} CLI contracts checked\n`);
} else {
  await writeFile(outputPath, generated);
  process.stdout.write(`Generated ${path.relative(repositoryDirectory, outputPath)} with ${variables.length} environment overrides\n`);
}
