func TestJobStore(t *testing.T, ss store.Store) {
	ctx := context.Background()
	at := model.NowUTC().Add(-time.Minute)
	job, err := model.NewJob(model.NewJobID(), model.JobTypeProfilePictureGenerateDefault, json.RawMessage(`{"user_id":"`+model.NewUserID().String()+`"}`), "user:first", at, at, 3)
	require.NoError(t, err)
	created, inserted, err := ss.Job().Enqueue(ctx, &store.JobEnqueue{Job: job})
	require.NoError(t, err)
	require.True(t, inserted, "Enqueue() = %#v", created)
	require.Equal(t, job.ID, created.ID, "Enqueue() = %#v", created)
	duplicate, inserted, err := ss.Job().Enqueue(ctx, &store.JobEnqueue{Job: mustJob(t, "user:first", at)})
	require.NoError(t, err)
	require.False(t, inserted, "deduplicated Enqueue() = %#v", duplicate)
	require.Equal(t, job.ID, duplicate.ID, "deduplicated Enqueue() = %#v", duplicate)

	_, err = ss.Job().ClaimNext(ctx, &store.JobClaimRequest{Types: []model.JobType{model.JobTypeCleanup}, NodeID: "node-a", ClaimToken: mustClaimToken(t), LeaseDuration: time.Minute})
	require.True(t, store.IsNotFound(err), "ClaimNext(other type) error")
	firstToken := mustClaimToken(t)
	claim, err := ss.Job().ClaimNext(ctx, &store.JobClaimRequest{Types: []model.JobType{job.Type}, NodeID: "node-a", ClaimToken: firstToken, LeaseDuration: time.Minute})
	require.NoError(t, err)
	require.Equal(t, model.JobStatusRunning, claim.Job.Status)
	require.Equal(t, 1, claim.Job.AttemptCount)
	require.Equal(t, 1, claim.Attempt.Number)
	require.Equal(t, firstToken, claim.Attempt.ClaimToken)
	reservation, err := ss.Job().ReserveWork(ctx, &store.JobWorkReservation{AttemptID: claim.Attempt.ID, ClaimToken: firstToken, Units: 2, Limit: 3})
	require.NoError(t, err)
	require.True(t, reservation.Reserved)
	require.Equal(t, 2, reservation.Consumed)
	reservation, err = ss.Job().ReserveWork(ctx, &store.JobWorkReservation{AttemptID: claim.Attempt.ID, ClaimToken: firstToken, Units: 2, Limit: 3})
	require.NoError(t, err)
	require.False(t, reservation.Reserved)
	require.Equal(t, 2, reservation.Consumed)
	_, err = ss.Job().Heartbeat(ctx, &store.JobHeartbeat{AttemptID: claim.Attempt.ID, ClaimToken: mustClaimToken(t), LeaseDuration: time.Minute})
	require.True(t, store.IsConflict(err), "Heartbeat(stale token) error")
	_, err = ss.Job().Heartbeat(ctx, &store.JobHeartbeat{AttemptID: claim.Attempt.ID, ClaimToken: firstToken, LeaseDuration: time.Minute})
	require.NoError(t, err)
	checkpointed, err := ss.Job().Checkpoint(ctx, &store.JobCheckpoint{AttemptID: claim.Attempt.ID, ClaimToken: firstToken, Progress: &model.JobProgress{Current: 1, Total: 3, Stage: "rendering"}, Checkpoint: json.RawMessage(`{"completed":1}`)})
	require.NoError(t, err)
	require.Equal(t, int64(1), checkpointed.Progress.Current)
	require.Equal(t, `{"completed":1}`, string(checkpointed.Checkpoint))
	retried, err := ss.Job().Complete(ctx, &store.JobCompletion{AttemptID: claim.Attempt.ID, ClaimToken: firstToken, Kind: store.JobCompletionRetryableFailure, RetryDelay: time.Millisecond, PublicErrorCode: "dependency.unavailable"})
	require.NoError(t, err)
	require.Equal(t, model.JobStatusQueued, retried.Status)
	require.True(t, retried.AvailableAt.After(retried.UpdatedAt))
	secondToken := mustClaimToken(t)
	time.Sleep(3 * time.Millisecond)
	second, err := ss.Job().ClaimNext(ctx, &store.JobClaimRequest{Types: []model.JobType{job.Type}, NodeID: "node-b", ClaimToken: secondToken, LeaseDuration: time.Minute})
	require.NoError(t, err)
	require.Equal(t, 2, second.Attempt.Number)
	require.Equal(t, 2, second.Job.WorkReserved)
	_, err = ss.Job().ReserveWork(ctx, &store.JobWorkReservation{AttemptID: claim.Attempt.ID, ClaimToken: firstToken, Units: 1, Limit: 3})
	require.True(t, store.IsConflict(err), "ReserveWork(stale attempt) error")
	reservation, err = ss.Job().ReserveWork(ctx, &store.JobWorkReservation{AttemptID: second.Attempt.ID, ClaimToken: secondToken, Units: 1, Limit: 3})
	require.NoError(t, err)
	require.True(t, reservation.Reserved)
	require.Equal(t, 3, reservation.Consumed)
	reservation, err = ss.Job().ReserveWork(ctx, &store.JobWorkReservation{AttemptID: second.Attempt.ID, ClaimToken: secondToken, Units: 1, Limit: 3})
	require.NoError(t, err)
	require.False(t, reservation.Reserved)
	require.Equal(t, 3, reservation.Consumed)
	_, err = ss.Job().Complete(ctx, &store.JobCompletion{AttemptID: claim.Attempt.ID, ClaimToken: firstToken, Kind: store.JobCompletionSucceeded, Result: json.RawMessage(`{}`)})
	require.True(t, store.IsConflict(err), "Complete(stale worker) error")
	succeeded, err := ss.Job().Complete(ctx, &store.JobCompletion{AttemptID: second.Attempt.ID, ClaimToken: secondToken, Kind: store.JobCompletionSucceeded, Result: json.RawMessage(`{"file_entry_id":"done"}`)})
	require.NoError(t, err)
	require.Equal(t, model.JobStatusSucceeded, succeeded.Status)
	require.True(t, succeeded.CompletedAt.Valid)
	attempts, err := ss.Job().ListAttempts(ctx, job.ID)
	require.NoError(t, err)
	require.Len(t, attempts, 2)
	require.Equal(t, model.JobAttemptStatusFailed, attempts[0].Status)
	require.Equal(t, model.JobAttemptStatusSucceeded, attempts[1].Status)

	relinquishable := mustJob(t, "worker:incompatible", model.NowUTC().Add(-time.Minute))
	_, _, err = ss.Job().Enqueue(ctx, &store.JobEnqueue{Job: relinquishable})
	require.NoError(t, err)
	relinquishToken := mustClaimToken(t)
	relinquishClaim, err := ss.Job().ClaimNext(ctx, &store.JobClaimRequest{Types: []model.JobType{relinquishable.Type}, NodeID: "old-primary-node", ClaimToken: relinquishToken, LeaseDuration: time.Minute})
	require.NoError(t, err)
	relinquished, err := ss.Job().Complete(ctx, &store.JobCompletion{AttemptID: relinquishClaim.Attempt.ID, ClaimToken: relinquishToken, Kind: store.JobCompletionRelinquished, RetryDelay: time.Millisecond, PublicErrorCode: "worker.capability_mismatch"})
	require.NoError(t, err)
	require.Equal(t, model.JobStatusQueued, relinquished.Status)
	require.Equal(t, 1, relinquished.AttemptCount)
	require.Equal(t, relinquishable.MaximumAttempts+1, relinquished.MaximumAttempts)
	require.Equal(t, relinquishable.MaximumAttempts, relinquished.MaximumAttempts-relinquished.AttemptCount)
	time.Sleep(3 * time.Millisecond)
	_, err = ss.Job().ClaimNext(ctx, &store.JobClaimRequest{Types: []model.JobType{relinquishable.Type}, NodeID: "old-primary-node", ClaimToken: mustClaimToken(t), LeaseDuration: time.Minute})
	require.True(t, store.IsNotFound(err), "incompatible node reclaimed relinquished Job")
	compatibleToken := mustClaimToken(t)
	compatibleClaim, err := ss.Job().ClaimNext(ctx, &store.JobClaimRequest{Types: []model.JobType{relinquishable.Type}, NodeID: "new-primary-node", ClaimToken: compatibleToken, LeaseDuration: time.Minute})
	require.NoError(t, err)
	require.Equal(t, relinquishable.ID, compatibleClaim.Job.ID, "compatible node claimed Job")
	_, err = ss.Job().Complete(ctx, &store.JobCompletion{AttemptID: compatibleClaim.Attempt.ID, ClaimToken: compatibleToken,
		Kind: store.JobCompletionSucceeded, Result: json.RawMessage(`{}`)})
	require.NoError(t, err)
	incompatibleAttempts, err := ss.Job().ListAttempts(ctx, relinquishable.ID)
	require.NoError(t, err)
	require.Len(t, incompatibleAttempts, 2)
	require.Equal(t, model.JobAttemptStatusIncompatible, incompatibleAttempts[0].Status)
	require.Equal(t, model.JobAttemptStatusSucceeded, incompatibleAttempts[1].Status)

	crashed := mustJob(t, "user:crashed", model.NowUTC().Add(-time.Minute))
	_, _, err = ss.Job().Enqueue(ctx, &store.JobEnqueue{Job: crashed})
	require.NoError(t, err)
	deadToken := mustClaimToken(t)
	dead, err := ss.Job().ClaimNext(ctx, &store.JobClaimRequest{Types: []model.JobType{crashed.Type}, NodeID: "dead-node", ClaimToken: deadToken, LeaseDuration: 200 * time.Millisecond})
	require.NoError(t, err)
	time.Sleep(250 * time.Millisecond)
	// Lease expiry requeues behind a backoff of at least the expired lease, so
	// work that crashed its worker is not handed straight to the next node.
	_, err = ss.Job().ClaimNext(ctx, &store.JobClaimRequest{Types: []model.JobType{crashed.Type}, NodeID: "live-node", ClaimToken: mustClaimToken(t), LeaseDuration: time.Minute})
	require.True(t, store.IsNotFound(err), "lease-expired Job was reclaimed without backoff")
	backedOff, err := ss.Job().Get(ctx, crashed.ID)
	require.NoError(t, err)
	require.Equal(t, model.JobStatusQueued, backedOff.Status)
	require.False(t, backedOff.AvailableAt.Before(backedOff.UpdatedAt.Add(200*time.Millisecond)), "lease-expiry backoff = %s", backedOff.AvailableAt.Sub(backedOff.UpdatedAt))
	time.Sleep(time.Until(backedOff.AvailableAt) + 50*time.Millisecond)
	recoveredToken := mustClaimToken(t)
	recovered, err := ss.Job().ClaimNext(ctx, &store.JobClaimRequest{Types: []model.JobType{crashed.Type}, NodeID: "live-node", ClaimToken: recoveredToken, LeaseDuration: time.Minute})
	require.NoError(t, err)
	require.Equal(t, crashed.ID, recovered.Job.ID)
	require.Equal(t, 2, recovered.Attempt.Number)
	_, err = ss.Job().Complete(ctx, &store.JobCompletion{AttemptID: dead.Attempt.ID, ClaimToken: deadToken, Kind: store.JobCompletionSucceeded, Result: json.RawMessage(`{}`)})
	require.True(t, store.IsConflict(err), "expired worker completion error")
	attempts, err = ss.Job().ListAttempts(ctx, crashed.ID)
	require.NoError(t, err)
	require.Equal(t, model.JobAttemptStatusLeaseExpired, attempts[0].Status)
	_, err = ss.Job().Complete(ctx, &store.JobCompletion{AttemptID: recovered.Attempt.ID, ClaimToken: recoveredToken, Kind: store.JobCompletionSucceeded, Result: json.RawMessage(`{}`)})
	require.NoError(t, err)

	exhaustedAt := model.NowUTC().Add(-time.Minute)
	exhausted, err := model.NewJob(model.NewJobID(), model.JobTypeProfilePictureGenerateDefault, json.RawMessage(`{"user_id":"`+model.NewUserID().String()+`"}`), "user:exhausted", exhaustedAt, exhaustedAt, 1)
	require.NoError(t, err)
	_, _, err = ss.Job().Enqueue(ctx, &store.JobEnqueue{Job: exhausted})
	require.NoError(t, err)
	_, err = ss.Job().ClaimNext(ctx, &store.JobClaimRequest{Types: []model.JobType{exhausted.Type}, NodeID: "last-node", ClaimToken: mustClaimToken(t), LeaseDuration: 10 * time.Millisecond})
	require.NoError(t, err)
	time.Sleep(20 * time.Millisecond)
	_, err = ss.Job().ClaimNext(ctx, &store.JobClaimRequest{Types: []model.JobType{exhausted.Type}, NodeID: "next-node", ClaimToken: mustClaimToken(t), LeaseDuration: time.Minute})
	require.True(t, store.IsNotFound(err), "ClaimNext(exhausted) error")
	exhausted, err = ss.Job().Get(ctx, exhausted.ID)
	require.NoError(t, err)
	require.Equal(t, model.JobStatusFailed, exhausted.Status)
	require.Equal(t, "job.lease_expired", exhausted.PublicErrorCode)
	require.True(t, exhausted.CompletedAt.Valid)
	repairAt := model.NowUTC().Add(-time.Second)
	repair := mustJob(t, "user:exhausted", repairAt)
	createdRepair, inserted, err := ss.Job().Enqueue(ctx, &store.JobEnqueue{Job: repair})
	require.NoError(t, err)
	require.True(t, inserted, "terminal repair Enqueue() = %#v", createdRepair)
	require.Equal(t, repair.ID, createdRepair.ID, "terminal repair Enqueue() = %#v", createdRepair)
	duplicateRepair, inserted, err := ss.Job().Enqueue(ctx, &store.JobEnqueue{Job: mustJob(t, "user:exhausted", repairAt)})
	require.NoError(t, err)
	require.False(t, inserted, "active repaired-job dedupe = %#v", duplicateRepair)
	require.Equal(t, repair.ID, duplicateRepair.ID, "active repaired-job dedupe = %#v", duplicateRepair)
	repairToken := mustClaimToken(t)
	repairClaim, err := ss.Job().ClaimNext(ctx, &store.JobClaimRequest{Types: []model.JobType{repair.Type}, NodeID: "repair-node", ClaimToken: repairToken, LeaseDuration: time.Minute})
	require.NoError(t, err)
	_, err = ss.Job().Complete(ctx, &store.JobCompletion{AttemptID: repairClaim.Attempt.ID, ClaimToken: repairToken, Kind: store.JobCompletionSucceeded, Result: json.RawMessage(`{}`)})
	require.NoError(t, err)

	permanentAt := model.NowUTC().Add(-time.Second)
	permanent := mustPermanentJob(t, "cleanup:2026-08-10", permanentAt)
	_, inserted, err = ss.Job().Enqueue(ctx, &store.JobEnqueue{Job: permanent})
	require.NoError(t, err)
	require.True(t, inserted, "first permanent occurrence was deduplicated")
	permanentToken := mustClaimToken(t)
	permanentClaim, err := ss.Job().ClaimNext(ctx, &store.JobClaimRequest{Types: []model.JobType{model.JobTypeCleanup}, NodeID: "cleanup-node", ClaimToken: permanentToken, LeaseDuration: time.Minute})
	require.NoError(t, err)
	terminalPermanent, err := ss.Job().Complete(ctx, &store.JobCompletion{AttemptID: permanentClaim.Attempt.ID, ClaimToken: permanentToken, Kind: store.JobCompletionSucceeded, Result: json.RawMessage(`{}`)})
	require.NoError(t, err)
	duplicatePermanent, inserted, err := ss.Job().Enqueue(ctx, &store.JobEnqueue{Job: mustPermanentJob(t, "cleanup:2026-08-10", permanentAt)})
	require.NoError(t, err)
	require.False(t, inserted, "terminal permanent-occurrence dedupe = %#v", duplicatePermanent)
	require.Equal(t, terminalPermanent.ID, duplicatePermanent.ID, "terminal permanent-occurrence dedupe = %#v", duplicatePermanent)
	require.Equal(t, model.JobStatusSucceeded, duplicatePermanent.Status, "terminal permanent-occurrence dedupe = %#v", duplicatePermanent)

	listed, err := ss.Job().List(ctx, store.JobListOptions{Types: []model.JobType{model.JobTypeProfilePictureGenerateDefault}, Limit: 2})
	require.NoError(t, err)
	require.Len(t, listed, 2)
	require.False(t, listed[0].CreatedAt.Before(listed[1].CreatedAt))
	nextPage, err := ss.Job().List(ctx, store.JobListOptions{Types: []model.JobType{model.JobTypeProfilePictureGenerateDefault}, BeforeCreatedAt: listed[1].CreatedAt, BeforeID: listed[1].ID, Limit: 20})
	require.NoError(t, err)
	for _, item := range nextPage {
		require.NotEqual(t, listed[0].ID, item.ID)
		require.NotEqual(t, listed[1].ID, item.ID)
	}

	control := mustJob(t, "user:control", model.NowUTC().Add(-time.Second))
	_, _, err = ss.Job().Enqueue(ctx, &store.JobEnqueue{Job: control})
	require.NoError(t, err)
	controlToken := mustClaimToken(t)
	controlClaim, err := ss.Job().ClaimNext(ctx, &store.JobClaimRequest{Types: []model.JobType{control.Type}, NodeID: "control-node", ClaimToken: controlToken, LeaseDuration: time.Minute})
	require.NoError(t, err)
	audit := saveJobMutationAudit(t, ctx, ss, control.ID, "cancel")
	cancelRequested, err := ss.Job().Cancel(ctx, &store.JobMutation{ID: control.ID, ExpectedRevision: controlClaim.Job.Revision, AuditEventID: audit.ID, AuditAt: model.NowUTC()})
	require.NoError(t, err)
	require.Equal(t, model.JobStatusCancelRequested, cancelRequested.Status)
	observed, err := ss.Job().CancellationRequested(ctx, controlClaim.Attempt.ID, controlToken)
	require.NoError(t, err)
	require.True(t, observed, "fenced worker did not observe cancellation")
	_, err = ss.Job().Complete(ctx, &store.JobCompletion{AttemptID: controlClaim.Attempt.ID, ClaimToken: controlToken, Kind: store.JobCompletionCanceled, PublicErrorCode: "job.canceled"})
	require.NoError(t, err)

	// A handler that fails retryably after cancellation was requested cannot
	// requeue; its completion honors the cancellation instead of being refused.
	retryCanceled := mustJob(t, "user:retry-canceled", model.NowUTC().Add(-time.Second))
	_, _, err = ss.Job().Enqueue(ctx, &store.JobEnqueue{Job: retryCanceled})
	require.NoError(t, err)
	retryCanceledToken := mustClaimToken(t)
	retryCanceledClaim, err := ss.Job().ClaimNext(ctx, &store.JobClaimRequest{Types: []model.JobType{retryCanceled.Type}, NodeID: "control-node", ClaimToken: retryCanceledToken, LeaseDuration: time.Minute})
	require.NoError(t, err)
	audit = saveJobMutationAudit(t, ctx, ss, retryCanceled.ID, "cancel")
	_, err = ss.Job().Cancel(ctx, &store.JobMutation{ID: retryCanceled.ID, ExpectedRevision: retryCanceledClaim.Job.Revision, AuditEventID: audit.ID, AuditAt: model.NowUTC()})
	require.NoError(t, err)
	canceledByRetry, err := ss.Job().Complete(ctx, &store.JobCompletion{AttemptID: retryCanceledClaim.Attempt.ID, ClaimToken: retryCanceledToken, Kind: store.JobCompletionRetryableFailure, RetryDelay: time.Second, PublicErrorCode: "dependency.unavailable"})
	require.NoError(t, err, "retryable completion after cancellation request")
	require.Equal(t, model.JobStatusCanceled, canceledByRetry.Status)
	require.Equal(t, "job.canceled", canceledByRetry.PublicErrorCode)

	failedJob := mustJob(t, "user:explicit-retry", model.NowUTC().Add(-time.Second))
	_, _, err = ss.Job().Enqueue(ctx, &store.JobEnqueue{Job: failedJob})
	require.NoError(t, err)
	failedToken := mustClaimToken(t)
	failedClaim, err := ss.Job().ClaimNext(ctx, &store.JobClaimRequest{Types: []model.JobType{failedJob.Type}, NodeID: "retry-node", ClaimToken: failedToken, LeaseDuration: time.Minute})
	require.NoError(t, err)
	failedJob, err = ss.Job().Complete(ctx, &store.JobCompletion{AttemptID: failedClaim.Attempt.ID, ClaimToken: failedToken, Kind: store.JobCompletionPermanentFailure, PublicErrorCode: "job.failed"})
	require.NoError(t, err)
	beforeAttempts, err := ss.Job().ListAttempts(ctx, failedJob.ID)
	require.NoError(t, err)
	audit = saveJobMutationAudit(t, ctx, ss, failedJob.ID, "retry")
	requeued, err := ss.Job().Retry(ctx, &store.JobMutation{ID: failedJob.ID, ExpectedRevision: failedJob.Revision, AuditEventID: audit.ID, AuditAt: model.NowUTC()})
	require.NoError(t, err)
	afterAttempts, err := ss.Job().ListAttempts(ctx, failedJob.ID)
	require.NoError(t, err)
	require.Equal(t, model.JobStatusQueued, requeued.Status, "Retry() = %#v, attempts %d ->", requeued, len(beforeAttempts))
	require.Len(t, afterAttempts, len(beforeAttempts), "Retry() = %#v, attempts %d ->", requeued, len(beforeAttempts))
}

func saveJobMutationAudit(t *testing.T, ctx context.Context, ss store.Store, jobID model.JobID, operation string) *model.AuditEvent {
	t.Helper()
	event, err := ss.Audit().Save(ctx, &model.AuditEvent{Action: string(model.ActionJobManage), Resource: model.Resource{Type: model.ResourceInstitution, ID: model.NewID()}, ScopeType: model.RoleScopeInstitution, ScopeID: model.NewID(), Status: model.AuditStatusAttempt, NodeID: "test-node", Parameters: []byte(`{"operation":"` + operation + `","job_id":"` + jobID.String() + `"}`)})
	require.NoError(t, err)
	return event
}

func mustJob(t *testing.T, dedupe string, at time.Time) *model.Job {
	t.Helper()
	job, err := model.NewJob(model.NewJobID(), model.JobTypeProfilePictureGenerateDefault, json.RawMessage(`{"user_id":"`+model.NewUserID().String()+`"}`), dedupe, at, at, 3)
	require.NoError(t, err)
	return job
}

func mustPermanentJob(t *testing.T, dedupe string, at time.Time) *model.Job {
	t.Helper()
	job, err := model.NewJobWithDedupePolicy(model.NewJobID(), model.JobTypeCleanup, json.RawMessage(`{}`), dedupe, model.JobDedupePermanent, at, at, 3)
	require.NoError(t, err)
	return job
}

func mustClaimToken(t *testing.T) model.JobClaimToken {
	t.Helper()
	token, err := model.NewJobClaimToken()
	require.NoError(t, err)
	return token
}
